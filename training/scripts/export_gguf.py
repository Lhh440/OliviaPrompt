"""M4 — merge LoRA adapter and export a quantized GGUF.

Three steps, each aborting loudly when its tool is missing:

1. merge    — ``llamafactory-cli export`` with a generated merge config
2. convert  — llama.cpp ``convert_hf_to_gguf.py`` → f16 GGUF
3. quantize — ``llama-quantize`` → Q4_K_M (lite) / Q5_K_M (standard)

Usage:
    python training/scripts/export_gguf.py --stage lite
    python training/scripts/export_gguf.py --stage standard --llama-cpp D:\\tools\\llama.cpp
Environment: LLAMA_CPP_DIR may replace --llama-cpp.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Dict, Optional

ROOT = Path(__file__).resolve().parents[2]

#: stage -> (config yaml, quantization, default gguf name)
STAGES: Dict[str, dict] = {
    "lite": {"config": ROOT / "training/configs/lite-4b.yaml",
             "quant": "Q4_K_M", "gguf": "olivia-lite-qwen3-4b"},
    "standard": {"config": ROOT / "training/configs/standard-8b.yaml",
                 "quant": "Q5_K_M", "gguf": "olivia-standard-qwen3-8b"},
}

MODELS_DIR = ROOT / "models"


def _models_dir(out: Optional[str]) -> Path:
    d = Path(out) if out else Path(os.environ.get("OLIVIA_MODELS_DIR", MODELS_DIR))
    d.mkdir(parents=True, exist_ok=True)
    return d


def read_yaml_simple(path: Path) -> Dict[str, str]:
    """Minimal `key: value` reader — the training configs are flat and we must
    not require pyyaml in the runtime venv."""
    out: Dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line or ":" not in line or line.startswith(("###", "-")):
            continue
        key, _, value = line.partition(":")
        out[key.strip()] = value.strip().strip('"')
    return out


def run(cmd: list, what: str) -> None:
    print(f"[export] {what}: {' '.join(str(c) for c in cmd)}")
    result = subprocess.run([str(c) for c in cmd])
    if result.returncode != 0:
        raise SystemExit(f"[export] {what} 失败，exit={result.returncode}")


def write_merge_config(config_path: Path, merged_dir: Path) -> Path:
    cfg = read_yaml_simple(config_path)
    merge_yaml = config_path.parent / f"merge-{config_path.stem}.yaml"
    merge_yaml.write_text(
        "\n".join([
            "### auto-generated by export_gguf.py — do not edit",
            f"model_name_or_path: {cfg.get('model_name_or_path', 'Qwen/Qwen3-4B')}",
            f"adapter_name_or_path: {cfg.get('output_dir', 'training/out/lite-4b')}",
            "template: " + cfg.get("template", "qwen3"),
            "finetuning_type: lora",
            f"export_dir: {merged_dir}",
            "export_size: 2",
            "export_device: cpu",
            "export_legacy_format: false",
            "",
        ]),
        encoding="utf-8",
    )
    return merge_yaml


def llama_cpp_tools(llama_cpp_dir: Path) -> tuple:
    convert = llama_cpp_dir / "convert_hf_to_gguf.py"
    quantize = None
    for name in ("llama-quantize.exe", "llama-quantize"):
        candidate = llama_cpp_dir / "build" / "bin" / name
        if candidate.exists():
            quantize = candidate
            break
        candidate = llama_cpp_dir / name
        if candidate.exists():
            quantize = candidate
            break
    missing = []
    if not convert.exists():
        missing.append(str(convert))
    if quantize is None:
        missing.append("llama-quantize (build/bin/llama-quantize.exe)")
    if missing:
        raise SystemExit(
            "找不到 llama.cpp 工具：\n  " + "\n  ".join(missing) +
            f"\n用 --llama-cpp 指向你的 llama.cpp 目录（当前: {llama_cpp_dir}）。\n"
            "克隆并编译: git clone https://github.com/ggml-org/llama.cpp && "
            "cmake -B build && cmake --build build --config Release"
        )
    return convert, quantize


def export(stage: str, llama_cpp_dir: Optional[Path], out_dir: Optional[str] = None) -> Path:
    if stage not in STAGES:
        raise SystemExit(f"unknown stage {stage!r}; choose from {sorted(STAGES)}")
    spec = STAGES[stage]
    config_path: Path = spec["config"]

    if shutil.which("llamafactory-cli") is None:
        raise SystemExit(
            "找不到 llamafactory-cli。先运行训练 venv（train.bat 会自动创建），"
            "或 pip install \"llamafactory[torch,metrics]\"。"
        )

    models_dir = _models_dir(out_dir)
    merged_dir = ROOT / "training" / "out" / f"merged-{stage}"
    merge_yaml = write_merge_config(config_path, merged_dir)

    run(["llamafactory-cli", "export", merge_yaml], "1/3 merge LoRA")
    if not merged_dir.exists():
        raise SystemExit(f"merge 输出目录不存在: {merged_dir}")

    convert, quantize = llama_cpp_tools(Path(llama_cpp_dir) if llama_cpp_dir
                                        else Path(os.environ.get("LLAMA_CPP_DIR", ".")))
    f16 = models_dir / f"{spec['gguf']}-f16.gguf"
    run([sys.executable, convert, merged_dir,
         "--outfile", f16, "--outtype", "f16"], "2/3 convert to GGUF")

    quantized = models_dir / f"{spec['gguf']}-{spec['quant'].lower()}.gguf"
    run([quantize, f16, quantized, spec["quant"]], "3/3 quantize")
    f16.unlink(missing_ok=True)

    print(f"\n完成: {quantized}")
    print(f"试跑: llama-server -m {quantized} --port 8081")
    print("然后: olivia-prompt ask \"...\" --base-url http://127.0.0.1:8081/v1 --model olivia")
    return quantized


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="LoRA → merged → GGUF 导出")
    ap.add_argument("--stage", default="lite", choices=sorted(STAGES))
    ap.add_argument("--llama-cpp", default=None, help="llama.cpp 目录（含 convert_hf_to_gguf.py 与编译产物）")
    ap.add_argument("--out", default=None, help="GGUF 输出目录（默认 ./models 或 OLIVIA_MODELS_DIR）")
    args = ap.parse_args(argv)
    export(args.stage, args.llama_cpp, args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
